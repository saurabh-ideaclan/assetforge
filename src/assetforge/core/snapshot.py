"""A shareable copy of the library (`assetforge library snapshot DEST`), meant to be committed to a git repo.

DEST gets a consistent copy of the catalog (SQLite backup API, so it is safe while the app runs) and the stored
files it references, minus everything that is local or can be rebuilt: jobs/, previews/, tmp/, logs/, backups,
SoundFonts and creature packs. WAV files are left out to keep the repo small:
- synthesized masters are pruned with `audio.masters.prune` (verified to re-render bit for bit), so a teammate's
  copy rebuilds them on demand exactly as in the publisher's library;
- every other WAV (an original added or imported as a file) is marked `withheld`: it stays only in the
  publisher's library. An asset whose primary file is withheld gets its OGG (else M4A/MP3) copy as primary.
The source library is only read. Re-running updates DEST in place: new files are copied, files no longer
referenced are removed, and WAVs left out last time are not copied again.
"""

from __future__ import annotations

import os
import re
import sqlite3
from pathlib import Path
from typing import TYPE_CHECKING, Any

from assetforge.core import db
from assetforge.core.util import dumps, loads, utcnow
from assetforge.errors import InvalidInputError, PolicyError

if TYPE_CHECKING:
    from assetforge.core.catalog import Library

LEFT_OUT = ("pruned", "withheld")
DELIVERY_ORDER = (".ogg", ".m4a", ".mp3")
SECRET = re.compile(rb"sk-[A-Za-z0-9_-]{20,}|AIza[0-9A-Za-z_-]{30,}|-----BEGIN [A-Z ]*PRIVATE KEY")

GITIGNORE = """\
# Generated by `assetforge library snapshot`. Local state that must not be shared.
.env
.env.*
*.env
catalog.sqlite3-wal
catalog.sqlite3-shm
catalog.sqlite3.tmp
tmp/
logs/
jobs/
previews/
exports/
backups/
# Re-rendered WAV masters and anything generated locally are not part of the snapshot.
objects/**/*.wav
.DS_Store
"""

GITATTRIBUTES = "catalog.sqlite3 binary\nobjects/** binary\n"

README = """\
# AssetForge asset library (shared snapshot)

Generated by `assetforge library snapshot`; do not edit by hand. It is a complete AssetForge library:
the catalog (`catalog.sqlite3`) and every stored file (`objects/`), without WAV masters.

## Use it

```bash
git clone <this repo> ~/assetforge-library
export ASSETFORGE_HOME=~/assetforge-library     # or pass --home ~/assetforge-library
assetforge search "green slime"                 # in the AssetForge repo: uv run assetforge …
```

- Synthesized sounds have no WAV master here; AssetForge re-renders it (bit for bit) the first time something
  needs it (processing, new export formats). Delivery copies (OGG, M4A) are already here.
- WAV originals that were added as files are kept only in the publisher's library; their OGG copy is the
  primary file here.

## Update

The catalog is one SQLite file, so it can't be merged. Anything you add or record in this copy is replaced
when you update:

```bash
git fetch origin && git reset --hard origin/main
```

Generate your own assets in your own library (`~/.assetforge`) if you want to keep them.
"""


def snapshot(lib: Library, dest: str | os.PathLike[str]) -> dict[str, Any]:
    """Write a shareable copy of `lib` into `dest` (created or updated). Returns a report."""
    from assetforge.core.catalog import Library

    target = Path(dest).expanduser().resolve()
    home = lib.paths.home.resolve()
    if target == home or home in target.parents or target in home.parents:
        raise InvalidInputError("The snapshot folder must be outside the library (and not contain it)", dest=str(target))
    if target.exists() and not target.is_dir():
        raise InvalidInputError(f"{target} is not a folder", dest=str(target))
    target.mkdir(parents=True, exist_ok=True)
    catalog = target / "catalog.sqlite3"
    carried = _left_out(catalog)

    tmp = target / "catalog.sqlite3.tmp"
    tmp.unlink(missing_ok=True)
    out = sqlite3.connect(tmp)
    try:
        lib.conn.backup(out)
    finally:
        out.close()
    if SECRET.search(tmp.read_bytes()):
        tmp.unlink()
        raise PolicyError("The catalog contains something that looks like an API key; nothing was written",
                          hint="Find it with: sqlite3 catalog.sqlite3 .dump | grep -nE 'sk-|AIza'")  # fmt: skip
    for stale in ("catalog.sqlite3-wal", "catalog.sqlite3-shm"):
        (target / stale).unlink(missing_ok=True)
    os.replace(tmp, catalog)

    report: dict[str, Any] = {"dest": str(target), "copied": 0, "copied_bytes": 0, "removed": 0,
                              "wav": {"pruned": 0, "pruned_bytes": 0, "carried": 0, "withheld": []}}  # fmt: skip
    copy = Library(target)
    try:
        rows = copy.conn.execute("SELECT sha256, rel_path, ext, size_bytes, extra FROM asset_files").fetchall()
        for row in rows:
            if row["ext"] == ".wav" and (flag := carried.get(row["sha256"])):
                _mark(copy, row["sha256"], flag)  # left out last time: no need to copy and re-check it
                report["wav"]["carried"] += 1
                continue
            if _flag(row["extra"]):
                continue  # already absent from the source library (e.g. pruned there)
            if not copy.store.abs_path(row["rel_path"]).is_file():
                stored = copy.store.put_file(lib.store.abs_path(row["rel_path"]), row["ext"], expected_sha256=row["sha256"])
                report["copied"] += stored.created
                report["copied_bytes"] += row["size_bytes"] if stored.created else 0

        from assetforge.audio import masters

        pruned = masters.prune(copy)  # re-renders each master first: only provably rebuildable ones go
        report["wav"]["pruned"], report["wav"]["pruned_bytes"] = pruned["count"], pruned["freed_bytes"]
        for row in copy.conn.execute("SELECT sha256, rel_path, extra FROM asset_files WHERE ext = '.wav'").fetchall():
            if not _flag(row["extra"]):
                _mark(copy, row["sha256"], "withheld")
                copy.store.abs_path(row["rel_path"]).unlink(missing_ok=True)
        report["wav"]["withheld"] = _withheld_primaries(copy)

        keep = {r["rel_path"] for r in copy.conn.execute("SELECT rel_path, extra FROM asset_files") if not _flag(r["extra"])}
        for path in copy.store.iter_objects():
            if copy.store.rel_path(path) not in keep:
                path.unlink()
                report["removed"] += 1
        copy.conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        report |= _totals(copy)
    finally:
        copy.close()

    for name, text in ((".gitignore", GITIGNORE), (".gitattributes", GITATTRIBUTES), ("README.md", README)):
        (target / name).write_text(text)
    return report


def _left_out(catalog: Path) -> dict[str, str]:
    """sha256 → 'pruned' | 'withheld' for files an earlier snapshot in this folder left out."""
    if not catalog.is_file():
        return {}
    conn = sqlite3.connect(f"file:{catalog}?mode=ro", uri=True)
    try:
        rows = conn.execute("SELECT sha256, extra FROM asset_files WHERE ext = '.wav'").fetchall()
    except sqlite3.Error:
        return {}
    finally:
        conn.close()
    return {sha: flag for sha, extra in rows if (flag := _flag(extra))}


def _flag(extra: str | None) -> str | None:
    """'pruned' or 'withheld' when the file is deliberately not in the library folder."""
    flags = loads(extra, {})
    return next((f for f in LEFT_OUT if flags.get(f)), None)


def _mark(lib: Library, sha256: str, flag: str) -> None:
    with db.transaction(lib.conn):
        row = lib.conn.execute("SELECT extra FROM asset_files WHERE sha256 = ?", (sha256,)).fetchone()
        extra = loads(row["extra"], {}) | {flag: True, f"{flag}_at": utcnow()}
        lib.conn.execute("UPDATE asset_files SET extra = ? WHERE sha256 = ?", (dumps(extra), sha256))


def _withheld_primaries(lib: Library) -> list[dict[str, Any]]:
    """Give each asset whose primary file was withheld its best delivery copy as primary."""
    rows = lib.conn.execute(
        "SELECT a.id, a.name, v.id AS variant_id, v.label, f.size_bytes, f.extra FROM assets a "
        "JOIN asset_variants v ON v.id = a.primary_variant_id JOIN asset_files f ON f.sha256 = v.file_sha256 "
        "WHERE f.ext = '.wav' ORDER BY a.id"
    ).fetchall()
    result = []
    for row in (r for r in rows if _flag(r["extra"]) == "withheld"):
        copies = {r["ext"]: r["id"] for r in lib.conn.execute(
            "SELECT v.id, f.ext FROM asset_variants v JOIN asset_files f ON f.sha256 = v.file_sha256 "
            "WHERE v.parent_variant_id = ? ORDER BY v.id", (row["variant_id"],))}  # fmt: skip
        primary = next((copies[ext] for ext in DELIVERY_ORDER if ext in copies), None)
        if primary:
            with db.transaction(lib.conn):
                lib.conn.execute("UPDATE assets SET primary_variant_id = ? WHERE id = ?", (primary, row["id"]))
        result.append({"asset_id": row["id"], "name": row["name"], "variant_id": row["variant_id"],
                       "label": row["label"], "bytes": row["size_bytes"], "primary": primary})  # fmt: skip
    return result


def _totals(lib: Library) -> dict[str, Any]:
    files = lib.store.iter_objects()
    return {"assets": lib.conn.execute("SELECT count(*) FROM assets").fetchone()[0], "files": len(files),
            "bytes": sum(p.stat().st_size for p in files)}  # fmt: skip
