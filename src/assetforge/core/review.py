"""Review workflow: a queue of candidates, QC-gated approval, and picking one candidate of a batch."""

from __future__ import annotations

from typing import Any

from assetforge.core import qc
from assetforge.core.catalog import Library
from assetforge.core.models import AssetSummary, AssetType, Status
from assetforge.core.util import normalize_optional_slug, qmarks
from assetforge.errors import InvalidInputError, PolicyError


def approve(
    lib: Library, refs: list[str], *, note: str | None = None, force: bool = False, primary: str | None = None
) -> dict[str, Any]:
    """Run QC on each asset first; refuse (POLICY_VIOLATION) if any has QC errors, unless forced."""
    if primary and len(refs) != 1:
        raise InvalidInputError("--primary can only be used when approving a single asset")
    asset_ids = [lib.resolve_asset_id(r) for r in refs]
    if primary:
        lib.set_primary_variant(asset_ids[0], primary)
    reports = [qc.check_asset(lib, asset_id) for asset_id in asset_ids]
    failing = [r for r in reports if not r["ok"]]
    if failing and not force:
        raise PolicyError(
            "QC errors block approval: " + "; ".join(f"{r['asset_id']}: {', '.join(r['errors'])}" for r in failing)
            + " (fix them, or pass --force)",
            failing=[{"asset_id": r["asset_id"], "errors": r["errors"]} for r in failing],
        )  # fmt: skip
    full_note = note if not failing else f"{note + '; ' if note else ''}approved despite QC errors (forced)"
    lib.set_status(asset_ids, Status.APPROVED, note=full_note)
    return {"status": Status.APPROVED.value, "asset_ids": asset_ids,
            "qc": [{"asset_id": r["asset_id"], "ok": r["ok"], "errors": r["errors"], "warnings": r["warnings"]}
                   for r in reports]}  # fmt: skip


def siblings(lib: Library, asset_id: str) -> list[str]:
    """Other assets generated by the same job (the alternatives a reviewer chooses between)."""
    row = lib.conn.execute(
        "SELECT json_extract(metadata, '$.generator.job_id') FROM assets WHERE id = ?", (asset_id,)
    ).fetchone()
    if not row or not row[0]:
        return []
    return [
        r[0]
        for r in lib.conn.execute(
            "SELECT id FROM assets WHERE json_extract(metadata, '$.generator.job_id') = ? AND id != ? ORDER BY id",
            (row[0], asset_id),
        )
    ]


def pick(lib: Library, ref: str, *, note: str | None = None, force: bool = False,
         primary: str | None = None) -> dict[str, Any]:  # fmt: skip
    """Approve one candidate and reject the other candidates from the same generation job."""
    asset_id = lib.resolve_asset_id(ref)
    result = approve(lib, [asset_id], note=note, force=force, primary=primary)
    others = [
        a for a in siblings(lib, asset_id)
        if lib.conn.execute("SELECT status FROM assets WHERE id = ?", (a,)).fetchone()[0] == Status.CANDIDATE.value
    ]  # fmt: skip
    if others:
        lib.set_status(others, Status.REJECTED, note=f"not picked; {asset_id} was chosen")
    return {**result, "rejected": others}


def queue(
    lib: Library,
    *,
    project: str | None = None,
    types: list[AssetType] | None = None,
    style: str | None = None,
    limit: int = 50,
) -> list[tuple[AssetSummary, dict[str, Any]]]:
    """Candidates awaiting review, oldest first, with their latest stored QC."""
    where, params = ["status = 'candidate'"], []
    if project := normalize_optional_slug(project, "project"):
        where.append("project = ?")
        params.append(project)
    if style := normalize_optional_slug(style, "style"):
        where.append("style = ?")
        params.append(style)
    if types:
        where.append(f"type IN ({qmarks(len(types))})")
        params += [t.value for t in types]
    rows = lib.conn.execute(
        f"SELECT id, json_extract(metadata, '$.qc') AS qc FROM assets WHERE {' AND '.join(where)} "
        "ORDER BY created_at, id LIMIT ?",
        [*params, limit],
    ).fetchall()
    import json

    stored = {r["id"]: json.loads(r["qc"]) if r["qc"] else {} for r in rows}
    return [(s, stored[s.id]) for s in lib.summaries([r["id"] for r in rows])]
