"""PixiJS v8 outputs: an `Assets.init({ manifest })` manifest, a sounds list, and TypeScript alias constants.

Textures use format expansion (`hero.{webp,png}`) so the resolver picks the best format the
browser supports. Atlases use `<name>.{webp,png}.json`. Audio is kept out of the Pixi manifest:
PixiJS core has no audio loader and would send `.ogg` to its video parser. `sounds.json` lists
alias → sources for `@pixi/sound` or any audio library.
"""

from __future__ import annotations

import json
from typing import Any


def _src(base: str, formats: list[str], suffix: str = "") -> str:
    if len(formats) == 1:
        return f"{base}.{formats[0]}{suffix}"
    return f"{base}.{{{','.join(formats)}}}{suffix}"


def manifest(
    bundle: str,
    *,
    textures: list[dict[str, Any]],
    atlases: list[dict[str, Any]],
    files: list[dict[str, Any]],
) -> dict[str, Any]:
    assets: list[dict[str, Any]] = []
    for t in textures:
        entry: dict[str, Any] = {"alias": t["alias"], "src": _src(t["alias"], t["formats"])}
        if t.get("data"):
            entry["data"] = t["data"]
        assets.append(entry)
    for a in atlases:
        first = a["pages"][0]["stem"]
        assets.append({"alias": a["name"], "src": _src(first, a["formats"], ".json")})
    for f in files:
        entry = {"alias": f["alias"], "src": f["path"]}
        if f.get("data"):
            entry["data"] = f["data"]
        assets.append(entry)
    return {"bundles": [{"name": bundle, "assets": sorted(assets, key=lambda e: e["alias"])}]}


def sounds(entries: list[dict[str, Any]]) -> dict[str, Any]:
    """Each sound: alias and sources, plus loop points (seconds), music facts, stems/intensity versions
    (`extras`, same length and timing as the main file) and round-robin `variations` when exported."""
    out = []
    for s in sorted(entries, key=lambda s: s["alias"]):
        item: dict[str, Any] = {"alias": s["alias"], "src": s["paths"]}
        if s.get("loop"):
            item |= {"loop": True, "loopStart": s["loop"]["start"], "loopEnd": s["loop"]["end"]}
        if s.get("music"):
            item |= s["music"]
        if s.get("extras"):
            item["extras"] = s["extras"]
        if s.get("variations"):
            item["variations"] = s["variations"]
        out.append(item)
    return {"sounds": out}


def typescript(bundle: str, *, textures: list[str], frames: list[str], animations: dict[str, list[str]],
               atlases: list[str], sounds_map: dict[str, list[str]]) -> str:  # fmt: skip
    def const(name: str, values: list[str]) -> str:
        return f"export const {name} = {json.dumps(sorted(values), indent=2)} as const;\n"

    return (
        "// Generated by AssetForge (`assetforge export`). Do not edit by hand.\n\n"
        f"export const BUNDLE = {json.dumps(bundle)};\n\n"
        + const("TEXTURES", textures)
        + "export type TextureAlias = (typeof TEXTURES)[number];\n\n"
        + const("ATLASES", atlases)
        + const("ATLAS_FRAMES", frames)
        + "export type FrameName = (typeof ATLAS_FRAMES)[number];\n\n"
        + f"export const ANIMATIONS = {json.dumps(dict(sorted(animations.items())), indent=2)} as const;\n\n"
        + f"export const SOUNDS = {json.dumps(dict(sorted(sounds_map.items())), indent=2)} as const;\n"
        + "export type SoundAlias = keyof typeof SOUNDS;\n"
    )
